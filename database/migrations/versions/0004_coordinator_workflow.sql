CREATE TABLE eventos_solicitud (
    id bigint GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_eventos_solicitud PRIMARY KEY,
    solicitud_id bigint NOT NULL CONSTRAINT fk_eventos_solicitud_solicitud_id_solicitudes REFERENCES solicitudes(id),
    actor_id bigint NOT NULL CONSTRAINT fk_eventos_solicitud_actor_id_usuarios REFERENCES usuarios(id),
    tipo varchar(30) NOT NULL,
    datos jsonb NOT NULL,
    fecha timestamptz NOT NULL DEFAULT now()
);
COMMENT ON COLUMN eventos_solicitud.id IS 'Identificador interno estable';
COMMENT ON COLUMN eventos_solicitud.fecha IS 'Fecha de creación en UTC';
CREATE INDEX ix_eventos_solicitud_orden ON eventos_solicitud (solicitud_id, id);
CREATE INDEX ix_eventos_solicitud_actor_id ON eventos_solicitud (actor_id);

CREATE FUNCTION eco_evento_solicitud() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE s solicitudes; a asignaciones; previous eventos_solicitud;
BEGIN
  SELECT * INTO s FROM solicitudes WHERE id=NEW.solicitud_id FOR UPDATE;
  IF s.estado NOT IN ('asignada','programada') OR eco_coordinador(s.colectivo_id) <> NEW.actor_id THEN
    RAISE EXCEPTION 'Evento fuera de estado o de colectivo' USING ERRCODE='23514';
  END IF;
  SELECT * INTO a FROM asignaciones WHERE solicitud_id=s.id;
  SELECT * INTO previous FROM eventos_solicitud WHERE solicitud_id=s.id ORDER BY id DESC LIMIT 1;
  IF a.id IS NULL OR (NEW.datos->>'recolector_id')::bigint IS DISTINCT FROM a.recolector_id OR NOT coalesce(
        (NEW.tipo='asignacion' AND s.estado='asignada'
          AND (previous.id IS NULL OR previous.datos->>'respuesta' IN ('rechazo','sin_respuesta')))
        OR (NEW.tipo='confirmacion' AND (previous.id IS NULL OR previous.tipo='asignacion'
          OR (previous.tipo='confirmacion' AND previous.datos->>'respuesta'<>'aceptacion'))
          AND NEW.datos->>'respuesta' IN ('aceptacion','rechazo','sin_respuesta','pendiente'))
        OR (NEW.tipo='programacion' AND s.estado='programada' AND a.programada_en IS NOT NULL
          AND (previous.tipo='incidencia' OR previous.datos->>'respuesta'='aceptacion'))
        OR (NEW.tipo IN ('recogida','incidencia') AND s.estado='programada'
          AND (previous.tipo='programacion' OR previous.datos->>'respuesta'='aceptacion'))
        OR (NEW.tipo='recepcion' AND previous.tipo='recogida')
        OR (NEW.tipo='pesaje' AND previous.tipo='recepcion'
          AND (NEW.datos->>'peso_real_kg')::numeric > 0
          AND (NEW.datos->>'peso_real_kg')::numeric < 'Infinity'::numeric), false) THEN
    RAISE EXCEPTION 'Evento operativo inválido para el responsable o el paso actual' USING ERRCODE='23514';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER evento_solicitud_validar BEFORE INSERT ON eventos_solicitud
  FOR EACH ROW EXECUTE FUNCTION eco_evento_solicitud();
CREATE TRIGGER evento_solicitud_inmutable BEFORE UPDATE OR DELETE ON eventos_solicitud
  FOR EACH ROW EXECUTE FUNCTION eco_inmutable();

CREATE OR REPLACE FUNCTION eco_asignacion() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE s solicitudes; actor bigint;
BEGIN
  SELECT * INTO s FROM solicitudes WHERE id=NEW.solicitud_id FOR UPDATE;
  actor := eco_coordinador(s.colectivo_id);
  IF NEW.coordinador_id<>actor OR s.estado NOT IN ('recibida','en_revision','asignada','programada') THEN
    RAISE EXCEPTION 'Asignación no autorizada o fuera de estado' USING ERRCODE='23514';
  END IF;
  IF TG_OP='UPDATE' THEN
    IF ROW(NEW.solicitud_id,NEW.colectivo_id) IS DISTINCT FROM ROW(OLD.solicitud_id,OLD.colectivo_id)
      OR (NEW.recolector_id<>OLD.recolector_id AND
          (s.estado NOT IN ('asignada','programada') OR NEW.programada_en IS NOT NULL OR
           coalesce((SELECT datos->>'respuesta' FROM eventos_solicitud WHERE solicitud_id=s.id
                      ORDER BY id DESC LIMIT 1), '') NOT IN ('rechazo','sin_respuesta'))) THEN
      RAISE EXCEPTION 'Reasignación fuera de estado' USING ERRCODE='23514';
    END IF;
  END IF;
  PERFORM 1 FROM recolectores WHERE id=NEW.recolector_id AND colectivo_id=s.colectivo_id AND activo FOR SHARE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Recolector ajeno o inactivo' USING ERRCODE='23514'; END IF;
  RETURN NEW;
END $$;

CREATE FUNCTION eco_recoleccion_pesaje() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NOT coalesce((SELECT tipo='pesaje' AND (datos->>'peso_real_kg')::numeric=NEW.peso_real_kg
      FROM eventos_solicitud WHERE solicitud_id=NEW.solicitud_id ORDER BY id DESC LIMIT 1), false) THEN
    RAISE EXCEPTION 'El cierre requiere el pesaje operativo registrado' USING ERRCODE='23514';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER recoleccion_pesaje_validar BEFORE INSERT ON recolecciones
  FOR EACH ROW EXECUTE FUNCTION eco_recoleccion_pesaje();
