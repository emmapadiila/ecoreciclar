"""Imprime documentación derivada de metadata; no conecta a la base ni muestra datos."""
import argparse
from sqlalchemy import UniqueConstraint
from sqlalchemy.dialects.postgresql import dialect
from backend.models import Base


def dictionary():
    print("# Diccionario de datos — EcoConecta 360\n")
    print("18 tablas de aplicación; `alembic_version` es infraestructura. Fuente: `backend/models.py`; esquema inicial congelado en la revisión 0001. Todos los identificadores son BIGINT GENERATED BY DEFAULT AS IDENTITY. Las FKs usan NO ACTION: no se borran históricos en cascada.\n")
    print("Los timestamps de eventos usan TIMESTAMPTZ; PostgreSQL almacena el instante y la API exige zona al programar. UTC en almacenamiento/sesiones; presentación America/Bogota en el panel. Las reglas adicionales de triggers se explican en [arquitectura](arquitectura.md).\n")
    for table in Base.metadata.sorted_tables:
        print(f"## {table.name}\n")
        print("| Columna | Tipo PostgreSQL | NULL | PK / FK | Índices y unicidad | Default | Justificación |")
        print("|---|---|---|---|---|---|---|")
        for col in table.columns:
            refs = (["PK"] if col.primary_key else []) + ["FK → " + fk.target_fullname for fk in sorted(col.foreign_keys, key=lambda fk: fk.target_fullname)]
            indices = [idx.name for idx in sorted(table.indexes, key=lambda idx: idx.name) if col.name in idx.columns]
            indices += [str(c.name) + " UNIQUE(" + ", ".join(c.columns.keys()) + ")" for c in table.constraints if isinstance(c, UniqueConstraint) and col.name in c.columns]
            if col.primary_key:
                indices.insert(0, str(table.primary_key.name))
            default = "IDENTITY" if col.identity else str(col.server_default.arg) if col.server_default else "—"
            print(f"| {col.name} | {col.type.compile(dialect=dialect())} | {'Sí' if col.nullable else 'No'} | {'; '.join(refs) or '—'} | {'; '.join(indices) or '—'} | {default} | {col.comment or '—'} |")
        checks = sorted((c for c in table.constraints if hasattr(c, "sqltext")), key=lambda c: str(c.name))
        if checks:
            print("\nRestricciones CHECK:\n")
            for constraint in checks:
                print(f"- `{constraint.name}`: `{constraint.sqltext}`.")
        print()


def erd():
    print("# Diagrama entidad–relación\n\nLas 18 tablas comparten una sola base PostgreSQL. La relación IA → solicitud es unidireccional. Las relaciones compuestas de asignación y recolección también se detallan en el [diccionario](modelo-datos.md).\n\n```mermaid\nerDiagram")
    for table in Base.metadata.sorted_tables:
        print(f"    {table.name} {{")
        for column in table.columns:
            kind = "bigint" if "INT" in str(column.type).upper() else "timestamptz" if "DATETIME" in str(column.type).upper() else "numeric" if "NUMERIC" in str(column.type).upper() else "jsonb" if "JSONB" in str(column.type) else "boolean" if "BOOLEAN" in str(column.type) else "text"
            flags = " PK" if column.primary_key else " FK" if column.foreign_keys else " UK" if column.unique else ""
            print(f"        {kind} {column.name}{flags}")
        print("    }")
    for table in Base.metadata.sorted_tables:
        for fk in sorted(table.foreign_key_constraints, key=lambda f: f.name):
            column = list(fk.columns)[0]
            parent = list(fk.elements)[0].column.table.name
            print(f'    {parent} {"|o" if column.nullable else "||"}--o{{ {table.name} : "{column.name}"')
    print("```\n\nLas cardinalidades de hijos están simplificadas: `recolecciones.solicitud_id`, `asignaciones.solicitud_id`, `movimientos_puntos.recoleccion_id` y `conversaciones.usuario_id` son UNIQUE (0..1). No existen borrados en cascada.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("document", choices=["dictionary", "erd"])
    argument = parser.parse_args()
    dictionary() if argument.document == "dictionary" else erd()
